/**
 * 图标尺寸标度。
 *
 * 收敛前全仓库有 19 种尺寸（9…64），其中 12~20 之间就占了七档——1px 的差别
 * 肉眼分辨不出，却让每一处对齐都要重新试。四档足够表达层级：
 *
 *   XS(12)  角标内部、极密集处，最小不再更小
 *   SM(14)  行内默认：按钮里、列表项里、正文旁
 *   MD(16)  强调：独立图标按钮、区块标题
 *   LG(20)  页面标题旁（跟着 text-lg / text-xl 走）
 *
 * 再往上（22+）是装饰性插画/空状态用的，不属于这套标度，按场景单给。
 */
export const ICON = {
  XS: 12,
  SM: 14,
  MD: 16,
  LG: 20,
} as const;

export type IconSize = (typeof ICON)[keyof typeof ICON];
