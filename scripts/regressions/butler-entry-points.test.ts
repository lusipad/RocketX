import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import test from 'node:test';
import { enUS } from '../../apps/web/src/i18n/locales/en-US';
import { zhCN } from '../../apps/web/src/i18n/locales/zh-CN';

test('管家保留新事项和项目历史，更多功能内保留拉取请求、已安排和插件', () => {
  const page = readFileSync('apps/web/src/pages/ButlerPage.tsx', 'utf8');
  const history = readFileSync('apps/web/src/components/ButlerConversationHistory.tsx', 'utf8');
  const workspace = readFileSync('apps/web/src/stores/codexWorkspace.ts', 'utf8');
  const ui = readFileSync('apps/web/src/stores/ui.ts', 'utf8');

  assert.match(page, /<ButlerConversationHistory \/>/);
  assert.match(page, /<ManagedSurface><ButlerRoutines \/><\/ManagedSurface>/);
  assert.match(page, /<ManagedSurface><ButlerPluginsPage \/><\/ManagedSurface>/);
  assert.doesNotMatch(page, /Dynamic|ButlerWorkspaceNav|今日纸|技能中心|身份中心/);

  assert.match(history, /aria-label=\{t\('butler\.history\.newConversation'\)\}/);
  assert.match(zhCN['butler.history.newConversation'], /新管家对话/);
  assert.ok(enUS['butler.history.newConversation'].trim());
  assert.match(history, /startThread\(\)/);
  assert.match(history, /resumeThread\(thread\.id\)/);
  assert.match(history, /aria-label=\{t\('butler\.history\.aiCollabAria'\)\}/);
  assert.match(zhCN['butler.history.aiCollabAria'], /AI 协作/);
  assert.ok(enUS['butler.history.aiCollabAria'].trim());
  assert.match(history, /t\('butler\.history\.hosted\.title'\)/);
  assert.match(zhCN['butler.history.hosted.title'], /AI 托管/);
  assert.ok(enUS['butler.history.hosted.title'].trim());
  assert.match(history, /aria-label=\{t\('butler\.history\.hosted\.listAria'\)\}/);
  assert.match(zhCN['butler.history.hosted.listAria'], /AI 托管会话/);
  assert.ok(enUS['butler.history.hosted.listAria'].trim());
  assert.match(history, />\{t\('butler\.history\.recentConversationsAndProjects'\)\}</);
  assert.match(zhCN['butler.history.recentConversationsAndProjects'], /最近对话与项目/);
  assert.ok(enUS['butler.history.recentConversationsAndProjects'].trim());
  assert.match(history, /className="work-first-more-features"/);
  assert.match(history, />\{t\('butler\.history\.personalProjects'\)\}</);
  assert.match(zhCN['butler.history.personalProjects'], /个人项目/);
  assert.ok(enUS['butler.history.personalProjects'].trim());
  assert.match(history, /aria-label=\{t\('butler\.history\.codexHistoryAria'\)\}/);
  assert.match(zhCN['butler.history.codexHistoryAria'], /Codex 对话历史/);
  assert.ok(enUS['butler.history.codexHistoryAria'].trim());
  assert.match(history, /setWorkbenchTab\('prs'\)/);
  assert.match(history, /t\('butler\.history\.navPullRequests'\)/);
  assert.match(zhCN['butler.history.navPullRequests'], /拉取请求/);
  assert.ok(enUS['butler.history.navPullRequests'].trim());
  assert.match(history, /t\('butler\.history\.navRoutines'\)/);
  assert.match(zhCN['butler.history.navRoutines'], /已安排/);
  assert.ok(enUS['butler.history.navRoutines'].trim());
  assert.match(history, /t\('butler\.history\.navPlugins'\)/);
  assert.match(zhCN['butler.history.navPlugins'], /插件/);
  assert.ok(enUS['butler.history.navPlugins'].trim());
  assert.match(history, /const projectEntries = useMemo/);
  assert.match(history, /aria-label=\{t\('butler\.history\.projectConfigAria', \{ label: entry\.label \}\)\}/);
  assert.match(zhCN['butler.history.projectConfigAria'], /项目配置：\{label\}/);
  assert.ok(enUS['butler.history.projectConfigAria'].trim());
  assert.match(history, /title=\{t\('butler\.history\.projectConfigTitle'\)\}/);
  assert.match(zhCN['butler.history.projectConfigTitle'], /项目配置/);
  assert.ok(enUS['butler.history.projectConfigTitle'].trim());
  assert.doesNotMatch(history, /setButlerView\('hosting'\)/);
  assert.doesNotMatch(history, /aria-label="任务"/);
  assert.doesNotMatch(history, /butler\.page\.tasksAria/);
  assert.doesNotMatch(history, /ButlerSessionSwitcher|today|memory|paper|manage/);

  assert.match(workspace, /importLegacyWorkspaceRoots\(legacyWorkspaceRoots\)/);
  assert.match(workspace, /runtime\.listThreads\(threadWorkspaceRoots\(get\(\)\)\)/);

  assert.match(ui, /aiRuntimeProvider: getAiRuntimeProvider\(\)/);
  assert.match(ui, /openButlerConversation: \(focusSessionKey\?: string\) => \{/);
  assert.doesNotMatch(ui, /setButlerTaskProvider|butlerTaskProviderPreference/);
  assert.match(ui, /butlerView: 'conversation'/);
  assert.match(ui, /selectedHostedSessionKey: focusSessionKey \?\? null/);
  assert.match(ui, /setButlerView: \(view\) => \{/);
  assert.match(ui, /module: 'butler-view',[\s\S]*butlerView: view/);
  assert.doesNotMatch(ui, /openButlerManage|openButlerPaper|butlerPaperDate|butlerConversationOpen|butlerManageOpen/);
});
