test('AI 托管在开启面板选择运行配置，并把选择快照写入会话', () => {
  const sharedAgent = readFileSync('apps/web/src/stores/sharedAgent.ts', 'utf8');
  const workspace = readFileSync('apps/web/src/stores/codexWorkspace.ts', 'utf8');
  const conversation = readFileSync('apps/web/src/components/ButlerConversation.tsx', 'utf8');
  const panel = readFileSync('apps/web/src/components/AgentPanel.tsx', 'utf8');
  const settings = readFileSync('apps/web/src/components/AiSettings.tsx', 'utf8');

  assert.match(sharedAgent, /const workspace = useCodexWorkspace\.getState\(\)/);
  assert.match(sharedAgent, /runtimeModel: options\.runtimeModel/);
  assert.match(sharedAgent, /runtimeEffort: options\.runtimeEffort/);
  assert.match(sharedAgent, /runtimePermissionPreset: options\.runtimePermissionPreset/);
  assert.match(sharedAgent, /permissionPreset: session\?\.runtimePermissionPreset \?\? workspace\.permissionPreset/);
  assert.match(panel, /aria-label=\{t\('agent\.panel\.modelAria'\)\}/);
  assert.match(zhCN['agent.panel.modelAria'], /AI 托管模型/);
  assert.ok(enUS['agent.panel.modelAria'].trim());
  assert.match(panel, /aria-label=\{t\('agent\.panel\.reasoningEffortAria'\)\}/);
  assert.match(zhCN['agent.panel.reasoningEffortAria'], /AI 托管推理强度/);
  assert.ok(enUS['agent.panel.reasoningEffortAria'].trim());
  assert.match(panel, /aria-label=\{t\('agent\.panel\.permissionAria'\)\}/);
  assert.match(zhCN['agent.panel.permissionAria'], /AI 托管权限/);
  assert.ok(enUS['agent.panel.permissionAria'].trim());
  assert.match(panel, /runtimeModel: hostingModel/);
  assert.match(panel, /runtimeEffort: hostingEffort/);
  assert.match(panel, /runtimePermissionPreset: hostingPermissionPreset/);
  assert.match(panel, /aria-label=\{t\('agent\.panel\.hostedProjectAria'\)\}/);
  assert.match(zhCN['agent.panel.hostedProjectAria'], /AI 托管项目/);
  assert.ok(enUS['agent.panel.hostedProjectAria'].trim());
  assert.match(panel, /nextCodexRuntimeSummary/);
  assert.match(panel, /activeCodexRuntimeSummary/);
  assert.doesNotMatch(workspace, /hostingModel/);
  assert.doesNotMatch(workspace, /hostingEffort/);
  assert.doesNotMatch(workspace, /setHostingModel/);
  assert.doesNotMatch(workspace, /setHostingEffort/);
  assert.doesNotMatch(conversation, /aria-label="AI 托管设置"/);
  assert.doesNotMatch(conversation, /ariaLabel="AI 托管模型"/);
  assert.doesNotMatch(conversation, /ariaLabel="AI 托管推理强度"/);
  assert.doesNotMatch(conversation, /agent\.panel\.modelAria|agent\.panel\.reasoningEffortAria|agent\.panel\.permissionAria/);
  assert.doesNotMatch(sharedAgent, /agentHostingSettings|getAgentHostingCodexSettings/);
  assert.doesNotMatch(settings, /AI 托管 Codex 模型|AI 托管 Codex 推理强度|AI 托管 Codex 权限/);
});

