test('开启托管会立即显示进度，并反馈跨设备前置检查失败', () => {
  const panel = readFileSync('apps/web/src/components/AgentPanel.tsx', 'utf8');

  assert.match(panel, /const startBlockReason/);
  assert.match(panel, /t\('agent\.panel\.block\.noAi'\)/);
  assert.match(zhCN['agent.panel.block.noAi'], /当前未启用 AI，请在设置中启用 Pi。/);
  assert.ok(enUS['agent.panel.block.noAi'].trim());
  assert.match(panel, /t\('agent\.panel\.block\.noProject'\)/);
  assert.match(zhCN['agent.panel.block.noProject'], /这台设备尚未添加托管项目/);
  assert.ok(enUS['agent.panel.block.noProject'].trim());
  assert.match(panel, /t\('agent\.panel\.block\.noModel'\)/);
  assert.match(zhCN['agent.panel.block.noModel'], /尚未读取到可用 Pi 模型/);
  assert.ok(enUS['agent.panel.block.noModel'].trim());
  assert.match(panel, /openDesktopDialog\(\{ directory: true, multiple: false, title: t\('agent\.panel\.pickProjectTitle'\) \}\)/);
  assert.match(zhCN['agent.panel.pickProjectTitle'], /选择 AI 托管项目/);
  assert.ok(enUS['agent.panel.pickProjectTitle'].trim());
  assert.match(panel, /ensureEnvironment\(\{ path \}\)/);
  assert.match(panel, /environmentIsBusy\(environment\.id, environmentState\.bindings\)/);
  assert.match(panel, /updateEnvironment\(environment\.id, \{ enabled: true \}\)/);
  assert.match(panel, /if \(!selectedProject\) \{\s*void addHostingProject\(\)/);
  assert.match(panel, /t\('agent\.panel\.addProjectBtn'\)/);
  assert.match(zhCN['agent.panel.addProjectBtn'], /添加托管项目/);
  assert.ok(enUS['agent.panel.addProjectBtn'].trim());
  assert.match(panel, /setStartingTmid\(tmid\)/);
  assert.match(panel, /setStartFailure/);
  assert.match(panel, /t\('agent\.panel\.startingBtn'\)/);
  assert.match(zhCN['agent.panel.startingBtn'], /正在开启…/);
  assert.ok(enUS['agent.panel.startingBtn'].trim());
  assert.match(panel, /role="alert"/);
  assert.match(panel, /role="status"/);
  assert.match(panel, /\.catch\(\(startError\) => \{[\s\S]*toast\.error\(startError, t\('agent\.panel\.startFailedToast'\)\);[\s\S]*\}\)/);
  assert.match(zhCN['agent.panel.startFailedToast'], /开启 AI 托管失败/);
  assert.ok(enUS['agent.panel.startFailedToast'].trim());
  assert.doesNotMatch(panel, /\.catch\(\(\) => undefined\)/);
});
