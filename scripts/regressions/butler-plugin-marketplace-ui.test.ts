import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import test from 'node:test';
import { enUS } from '../../apps/web/src/i18n/locales/en-US';
import { zhCN } from '../../apps/web/src/i18n/locales/zh-CN';

test('插件页读取原生插件、Skill、App 目录，并通过 AppServerController 调用稳定协议', () => {
  const page = readFileSync('apps/web/src/components/ButlerPluginsPage.tsx', 'utf8');
  const workspace = readFileSync('apps/web/src/stores/codexWorkspace.ts', 'utf8');
  const controller = readFileSync('apps/web/src/agent/AppServerController.ts', 'utf8');

  assert.match(page, /const \[activeTab, setActiveTab\] = useState<CatalogTab>\('plugins'\)/);
  assert.match(page, /\['plugins', 'butler\.plugins\.tabPlugins'\]/);
  assert.match(zhCN['butler.plugins.tabPlugins'], /^插件$/);
  assert.ok(enUS['butler.plugins.tabPlugins'].trim());
  assert.match(page, /\['skills', 'butler\.plugins\.tabSkills'\]/);
  assert.match(zhCN['butler.plugins.tabSkills'], /^Skills$/);
  assert.ok(enUS['butler.plugins.tabSkills'].trim());
  assert.match(page, /\['apps', 'butler\.plugins\.tabApps'\]/);
  assert.match(zhCN['butler.plugins.tabApps'], /^Apps$/);
  assert.ok(enUS['butler.plugins.tabApps'].trim());
  assert.match(page, /type PluginDirectoryTab = 'public' \| 'workspace' \| 'personal'/);
  assert.match(page, /\['public', 'butler\.plugins\.dirPublic'\]/);
  assert.match(zhCN['butler.plugins.dirPublic'], /^公开$/);
  assert.ok(enUS['butler.plugins.dirPublic'].trim());
  assert.match(page, /\['workspace', 'butler\.plugins\.dirWorkspace'\]/);
  assert.match(zhCN['butler.plugins.dirWorkspace'], /^工作区$/);
  assert.ok(enUS['butler.plugins.dirWorkspace'].trim());
  assert.match(page, /\['personal', 'butler\.plugins\.dirPersonal'\]/);
  assert.match(zhCN['butler.plugins.dirPersonal'], /^个人$/);
  assert.ok(enUS['butler.plugins.dirPersonal'].trim());
  assert.match(page, /const installedPlugins =/);
  assert.match(page, />\{t\('butler\.plugins\.installedGroupHeading'\)\}</);
  assert.match(zhCN['butler.plugins.installedGroupHeading'], /^已安装$/);
  assert.ok(enUS['butler.plugins.installedGroupHeading'].trim());
  assert.match(page, /t\('butler\.plugins\.loadingCatalog'\)/);
  assert.match(zhCN['butler.plugins.loadingCatalog'], /正在读取 Codex 目录/);
  assert.ok(enUS['butler.plugins.loadingCatalog'].trim());
  assert.match(page, /t\('butler\.plugins\.noWorkspaceDesc'\)/);
  assert.match(zhCN['butler.plugins.noWorkspaceDesc'], /真实的插件、Skills 和 Apps 目录/);
  assert.ok(enUS['butler.plugins.noWorkspaceDesc'].trim());
  assert.match(page, /'butler\.plugins\.appsCatalogUnavailable'/);
  assert.match(zhCN['butler.plugins.appsCatalogUnavailable'], /Apps 目录暂不可用/);
  assert.ok(enUS['butler.plugins.appsCatalogUnavailable'].trim());
  assert.match(page, /t\('butler\.plugins\.catalogErrorFallbackHint'\)/);
  assert.match(zhCN['butler.plugins.catalogErrorFallbackHint'], /对话、Skills 和已安排任务仍可正常使用/);
  assert.ok(enUS['butler.plugins.catalogErrorFallbackHint'].trim());
  assert.match(page, /togglePlugin/);
  assert.match(page, /toggleSkill/);
  assert.match(page, /aria-label=\{t\('butler\.plugins\.viewSkillAria', \{ title \}\)\}/);
  assert.match(zhCN['butler.plugins.viewSkillAria'], /查看 Skill \{title\}/);
  assert.ok(enUS['butler.plugins.viewSkillAria'].trim());
  assert.match(page, /aria-label=\{t\('butler\.plugins\.viewAppAria', \{ name: app\.name \}\)\}/);
  assert.match(zhCN['butler.plugins.viewAppAria'], /查看 App \{name\}/);
  assert.ok(enUS['butler.plugins.viewAppAria'].trim());
  assert.match(page, /selectedItem\.kind === 'plugin'/);
  assert.match(page, /selectedItem\.kind === 'skill'/);
  assert.match(page, /kind: 'app', app/);
  assert.match(page, /desktopAssetUrl/);
  assert.match(page, /function CatalogIcon/);
  assert.match(page, /plugin\.interface\?\.composerIcon/);
  assert.match(page, /plugin\.interface\?\.composerIconUrl/);
  assert.match(page, /plugin\.interface\?\.logoDark/);
  assert.match(page, /plugin\.interface\?\.logoUrlDark/);
  assert.match(page, /selectedItem\.detailError/);
  assert.match(page, /t\('butler\.plugins\.detailErrorHint'\)/);
  assert.match(zhCN['butler.plugins.detailErrorHint'], /更多详情暂不可用/);
  assert.ok(enUS['butler.plugins.detailErrorHint'].trim());
  assert.match(page, /\{t\('common\.retry'\)\}/);
  assert.match(zhCN['common.retry'], /^重试$/);
  assert.ok(enUS['common.retry'].trim());
  assert.doesNotMatch(page, /只使用稳定的 skills\/list|插件市场协议已禁用|Memory 由 Codex 自动维护/);

  const detailHandler = page.slice(page.indexOf('const openPluginDetail'), page.indexOf('\n\n  return ('));
  assert.match(detailHandler, /detailError: true/);
  assert.doesNotMatch(detailHandler, /toast\.error/);

  assert.match(workspace, /installPlugin: async \(marketplace, pluginName\) => \{/);
  assert.match(workspace, /uninstallPlugin: async \(pluginId\) => \{/);
  assert.match(workspace, /setSkillEnabled: async \(path, enabled\) => \{/);
  assert.match(workspace, /await get\(\)\.refreshCatalog\(\)/);

  assert.match(controller, /client\.request\('skills\/list', \{ cwds: \[workspaceRoot\], forceReload: true \}\)/);
  assert.match(controller, /const optional = <T>\(request: Promise<T>\)/);
  assert.match(controller, /await Promise\.all\(\[/);
  assert.match(controller, /optional\(client\.request\('app\/list'/);
  assert.match(controller, /optional\(client\.request\('plugin\/list'/);
  assert.match(controller, /client\.request\('app\/list', \{ threadId, forceRefetch: true \}\)/);
  assert.match(controller, /client\.request\('plugin\/list', \{ cwds: \[workspaceRoot\] \}\)/);
  assert.match(controller, /catalogErrors/);
  assert.match(controller, /request\('plugin\/install', \{ remoteMarketplaceName, pluginName \}\)/);
  assert.match(controller, /request\('plugin\/uninstall', \{ pluginId \}\)/);
  assert.match(controller, /request\('plugin\/read', \{ remoteMarketplaceName, pluginName \}\)/);
});
